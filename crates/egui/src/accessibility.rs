        | Role::DocCover
        | Role::DocCredit
        | Role::DocCredits
        | Role::DocDedication
        | Role::DocEndnote
        | Role::DocEndnotes
        | Role::DocEpigraph
        | Role::DocEpilogue
        | Role::DocErrata
        | Role::DocExample
        | Role::DocFootnote
        | Role::DocForeword
        | Role::DocGlossary
        | Role::DocGlossRef
        | Role::DocIndex
        | Role::DocIntroduction
        | Role::DocNoteRef
        | Role::DocNotice
        | Role::DocPageBreak
        | Role::DocPageFooter
        | Role::DocPageHeader
        | Role::DocPageList
        | Role::DocPart
        | Role::DocPreface
